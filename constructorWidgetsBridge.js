const AVAILABLE_WIDGETS = {
    aspects:  '🧠 ASPECTS-10',
    liver:    '🫀 Печень (Couinaud)',
    bile:     '💧 Желчевыводящая',
    pancreas: '🫁 Поджелудочная',
    spleen:   '🩸 Селезёнка',
    adrenal:  '🫘 Надпочечники',
    urinary:  '🫘 Мочевая система'
};

// ============================================================
// УМНОЕ ОТКРЫТИЕ (по ID напрямую)
// ============================================================
function openWidgetSmart(widgetId) {
    if (!widgetId) {
        toast('Виджет не указан', 'error');
        return;
    }

    if (typeof openWidget === 'function') {
        openWidget(widgetId);
    } else {
        toast('Виджет не найден', 'error');
    }
}

// ============================================================
// ПОЛУЧИТЬ СПИСОК ВСЕХ ДОСТУПНЫХ ВИДЖЕТОВ
// ============================================================
function getAvailableWidgets() {
    return Object.entries(AVAILABLE_WIDGETS).map(([id, name]) => ({ id, name }));
}